# Generates src/geo.js from real circuit outlines (tools/geo/*.geojson, MIT licence,
# github.com/bacinger/f1-circuits). Each outline is converted to metres, put in racing
# direction, started on the start/finish line, smoothed, scaled to the official lap length
# and rotated so the start heading is +x.  Usage: python3 -I tools/circuitgen.py
import json, math, os
HERE = os.path.dirname(os.path.abspath(__file__))
CFG = {  # game id: (file, official length m, reverse, start offset m along the data lap)
    'parco':    ('it-1922', 5793, False, 0),
    'riviera':  ('mc-1929', 3337, False, 2350),
    'sakura':   ('jp-1962', 5807, False, 0),
    'ardennes': ('be-1925', 7004, False, 0),
    'airfield': ('gb-1948', 5891, False, 3180),
    'serra':    ('br-1940', 4309, False, 0),
    'neon':     ('sg-2008', 4927, True, 4830),
}
STEP = 5.0
def load(fn):
    g = json.load(open(os.path.join(HERE, 'geo', fn + '.geojson')))
    geom = g['features'][0]['geometry']
    c = geom['coordinates'] if geom['type'] == 'LineString' else geom['coordinates'][0]
    lat0 = sum(q[1] for q in c) / len(c); lon0 = sum(q[0] for q in c) / len(c); R = 6371000.0
    p = [((q[0] - lon0) * math.pi / 180 * R * math.cos(lat0 * math.pi / 180), -(q[1] - lat0) * math.pi / 180 * R) for q in c]
    if math.dist(p[0], p[-1]) < 1: p = p[:-1]
    return p
def resample(p, step):
    out = []; acc = 0.0; P = p + [p[0]]
    for k in range(len(p)):
        a, b = P[k], P[k + 1]; L = math.dist(a, b)
        while acc <= L:
            f = acc / L if L else 0; out.append((a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f)); acc += step
        acc -= L
    return out
def smooth(p, it):
    n = len(p)
    for _ in range(it):
        p = [((p[i - 1][0] + 2 * p[i][0] + p[(i + 1) % n][0]) / 4, (p[i - 1][1] + 2 * p[i][1] + p[(i + 1) % n][1]) / 4) for i in range(n)]
    return p
out = {}
for gid, (fn, Lreal, rev, off) in CFG.items():
    p = load(fn)
    if rev: p = p[::-1]
    p = smooth(resample(p, STEP), 12)
    L = sum(math.dist(p[k], p[(k + 1) % len(p)]) for k in range(len(p)))
    k0 = int(round(off / L * len(p))) % len(p)
    p = p[k0:] + p[:k0]
    sc = Lreal / L
    x0, z0 = p[0]
    h = math.atan2(p[3][1] - p[-3][1], p[3][0] - p[-3][0])
    ch, sh = math.cos(-h), math.sin(-h)
    q = [(((x - x0) * ch - (z - z0) * sh) * sc, ((x - x0) * sh + (z - z0) * ch) * sc) for x, z in p]
    # corner list in final lap metres (for naming in src/circuits.js)
    n = len(q); hd = [math.atan2(q[(i + 1) % n][1] - q[i][1], q[(i + 1) % n][0] - q[i][0]) for i in range(n)]
    dh = [((hd[i] - hd[i - 1] + math.pi) % (2 * math.pi)) - math.pi for i in range(n)]
    ds = Lreal / n; kap = [sum(dh[(i + j) % n] for j in range(-4, 5)) / (ds * 9) for i in range(n)]
    cs = []; inC = False
    for i in range(n + 1):
        ii = i % n; c = i < n and abs(kap[ii]) > 1 / 400
        if inC and (not c or (kap[ii] > 0) != sg):
            ang = sum(dh[j] for j in range(st, i)) * 180 / math.pi
            if abs(ang) > 12: cs.append('%d-%d %s%d r%d' % (st * ds, i * ds, 'R' if ang > 0 else 'L', abs(ang), min(1 / max(abs(kap[j]), 1e-6) for j in range(st, i))))
            inC = False
        if c and not inC: st = i; sg = kap[ii] > 0; inC = True
    print('  ', ' | '.join(cs))
    q = q[::3]
    out[gid] = [[round(a, 1), round(b, 1)] for a, b in q]
    print(gid, fn, 'pts', len(q), 'scale %.4f' % sc)
with open(os.path.join(HERE, '..', 'src', 'geo.js'), 'w') as f:
    lic = open(os.path.join(HERE, 'geo', 'LICENSE-bacinger-f1-circuits.md')).read().strip()
    f.write('// Generated by tools/circuitgen.py from real circuit outlines. Do not edit by hand.\n')
    f.write('/*! Circuit outlines derived from https://github.com/bacinger/f1-circuits\n' + lic.replace('*/', '* /') + '\n*/\n')
    f.write('export const GEO = ' + json.dumps(out, separators=(',', ':')) + ';\n')
