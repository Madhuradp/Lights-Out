# Packs real sky HDRIs (Poly Haven, CC0, via github.com/pmndrs/assets) into src/envmaps.js
# for image-based reflections and lighting. Each is box-filtered to 256x128, its sun is
# clamped (stops speckled highlights), it is normalised to a common brightness, and stored as
# an RGBE PNG data URI (alpha = shared exponent). Also records the sun's azimuth/elevation so
# the game can rotate the sky to match its own sun.  Usage: python3 -I tools/envgen.py
import cv2, numpy as np, base64, json, os, math
HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = ['park', 'venice', 'sunrise', 'forest']
W, H = 256, 128
out = {}
for n in NAMES:
    im = cv2.imread(os.path.join(HERE, 'env', n + '.hdr'), cv2.IMREAD_UNCHANGED)[:, :, ::-1].astype(np.float32)  # RGB
    lum = im @ np.array([0.2126, 0.7152, 0.0722], np.float32)
    y, x = np.unravel_index(np.argmax(lum), lum.shape)
    az = (x + 0.5) / im.shape[1] * 2 * math.pi; el = (0.5 - (y + 0.5) / im.shape[0]) * math.pi
    small = cv2.resize(im, (W, H), interpolation=cv2.INTER_AREA)
    l2 = small @ np.array([0.2126, 0.7152, 0.0722], np.float32)
    small *= (0.55 / max(1e-4, np.median(l2)))
    small = np.minimum(small, 14.0)
    # RGBE
    m = small.max(axis=2); e = np.ceil(np.log2(np.maximum(m, 1e-12))); e = np.clip(e, -128, 127)
    scale = 255.0 / np.power(2.0, e)
    rgb = np.clip(small * scale[..., None], 0, 255).astype(np.uint8)
    ex = (e + 128).astype(np.uint8); ex[m < 1e-9] = 0
    rgba = np.dstack([rgb, ex])
    ok, png = cv2.imencode('.png', cv2.cvtColor(rgba, cv2.COLOR_RGBA2BGRA), [cv2.IMWRITE_PNG_COMPRESSION, 9])
    out[n] = {'uri': 'data:image/png;base64,' + base64.b64encode(png.tobytes()).decode(), 'sunAz': round(az, 3), 'sunEl': round(el, 3)}
    print(n, len(png), 'bytes, sun az %.0f el %.0f deg' % (math.degrees(az), math.degrees(el)))
with open(os.path.join(HERE, '..', 'src', 'envmaps.js'), 'w') as f:
    f.write('// Generated by tools/envgen.py. Sky HDRIs from Poly Haven (polyhaven.com), CC0, via github.com/pmndrs/assets.\n')
    f.write('export const ENVMAPS = ' + json.dumps(out) + ';\n')
